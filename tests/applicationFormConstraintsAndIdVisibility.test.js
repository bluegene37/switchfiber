import { test, describe } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { isSystemField } from '../src/models/requiredFields.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const tableFile = path.resolve(__dirname, '../src/components/DynamicApiTable.vue')
const src = fs.readFileSync(tableFile, 'utf8')

// Emulate helper functions from DynamicApiTable.vue
const sanitizeDocLimit = (val, fallback = 'document.jpg') => {
  if (!val) return ''
  const str = String(val).trim()
  if (!str) return ''
  if ((str.startsWith('http://') || str.startsWith('https://')) && str.length <= 255) {
    return str
  }
  if (str.startsWith('data:') || str.length > 255) {
    return fallback
  }
  return str.slice(0, 255)
}

const capStr = (val, max = 255) => {
  if (val === null || val === undefined) return ''
  return String(val).trim().slice(0, max)
}

function isAuditField(col, isApplication = false) {
  if (!col) return false
  const lower = col.toLowerCase().replace(/_/g, '')
  return (
    lower === 'id' ||
    (isApplication && (lower === 'applicationid' || lower === 'applicationidvalue')) ||
    lower === 'createdby' ||
    lower === 'modifiedby' ||
    lower === 'timestamp' ||
    lower === 'rowversion'
  )
}

describe('Applications Endpoint: Autogenerated Application ID Visibility', () => {
  test('isSystemField recognizes applicationid and applicationidvalue as system fields', () => {
    assert.ok(isSystemField('applicationid'), 'applicationid must be recognized as system field')
    assert.ok(isSystemField('applicationId'), 'applicationId must be recognized as system field')
    assert.ok(isSystemField('application_id'), 'application_id must be recognized as system field')
    assert.ok(isSystemField('applicationidvalue'), 'applicationidvalue must be recognized as system field')
  })

  test('isAuditField in DynamicApiTable.vue checks isApplicationEndpoint for applicationid and applicationidvalue', () => {
    assert.ok(
      src.includes("(isApplicationEndpoint.value && (lower === 'applicationid' || lower === 'applicationidvalue'))"),
      'isAuditField must treat applicationid and applicationidvalue as audit fields on Applications'
    )
  })

  test('applicationid is recognized as audit field for Applications but not for other endpoints', () => {
    assert.equal(isAuditField('applicationid', true), true, 'applicationid must be audit field for Applications')
    assert.equal(isAuditField('applicationId', true), true, 'applicationId must be audit field for Applications')
    assert.equal(isAuditField('application_id', true), true, 'application_id must be audit field for Applications')
    assert.equal(isAuditField('applicationidvalue', true), true, 'applicationidvalue must be audit field for Applications')
    assert.equal(isAuditField('applicationid', false), false, 'applicationid is not audit field for non-Applications')
  })

  test('formatLabel customOverrides has human-readable label for Application ID', () => {
    assert.ok(src.includes("applicationid: 'Application ID'"), 'applicationid override must exist')
    assert.ok(src.includes("applicationidvalue: 'Application ID'"), 'applicationidvalue override must exist')
  })
})

describe('Applications Endpoint: SQL Server Column Truncation Prevention (500 Error Fix)', () => {
  test('sanitizeDocLimit converts base64 data URIs to clean filename <= 255 chars', () => {
    const hugeBase64 = 'data:image/jpeg;base64,' + 'A'.repeat(50000)
    assert.equal(sanitizeDocLimit(hugeBase64, 'house_front_photo.jpg'), 'house_front_photo.jpg')
    assert.equal(sanitizeDocLimit(hugeBase64, 'second_valid_id.jpg'), 'second_valid_id.jpg')
  })

  test('sanitizeDocLimit preserves valid URLs <= 255 chars', () => {
    const url = 'https://switchfiber.ph/uploads/house.jpg'
    assert.equal(sanitizeDocLimit(url, 'house_front_photo.jpg'), url)
  })

  test('sanitizeDocLimit converts overly long string (> 255 chars) to fallback', () => {
    const longString = 'x'.repeat(300)
    assert.equal(sanitizeDocLimit(longString, 'document.jpg'), 'document.jpg')
  })

  test('sanitizeDocLimit handles empty or null values cleanly', () => {
    assert.equal(sanitizeDocLimit('', 'fallback.jpg'), '')
    assert.equal(sanitizeDocLimit(null, 'fallback.jpg'), '')
    assert.equal(sanitizeDocLimit(undefined, 'fallback.jpg'), '')
  })

  test('capStr truncates text overflowing SQL Server column lengths', () => {
    const longText = 'A'.repeat(500)
    assert.equal(capStr(longText, 255).length, 255)
    assert.equal(capStr(longText, 100).length, 100)
    assert.equal(capStr(longText, 20).length, 20)
    assert.equal(capStr(null, 100), '')
    assert.equal(capStr(undefined, 100), '')
  })

  test('DynamicApiTable.vue applies sanitizeDocLimit to houseFrontPicture, secondGovernmentValidId, and billing statement in saveData', () => {
    assert.ok(
      src.includes("houseFrontPicture: sanitizeDocLimit(payload.houseFrontPicture, 'house_front_photo.jpg')"),
      'saveData must sanitize houseFrontPicture'
    )
    assert.ok(
      src.includes("secondGovernmentValidId: sanitizeDocLimit(payload.secondGovernmentValidId, 'second_valid_id.jpg')"),
      'saveData must sanitize secondGovernmentValidId'
    )
  })

  test('DynamicApiTable.vue applies sanitizeDocLimit in updateRecord', () => {
    const matches = (src.match(/sanitizeDocLimit\(payload\.houseFrontPicture, 'house_front_photo\.jpg'\)/g) || []).length
    assert.equal(matches, 2, 'sanitizeDocLimit for houseFrontPicture must be used in both saveData and updateRecord')
  })

  test('DynamicApiTable.vue caps remarks and address fields to 255 in Applications payloads', () => {
    assert.ok(src.includes("installationAddress: capStr(payload.installationAddress, 255)"), 'installationAddress capped at 255')
    assert.ok(src.includes("remarks: capStr(withPhotoGps('create', payload.remarks), 255)"), 'create remarks capped at 255')
    assert.ok(src.includes("remarks: capStr(withPhotoGps('edit', payload.remarks), 255)"), 'edit remarks capped at 255')
  })
})
