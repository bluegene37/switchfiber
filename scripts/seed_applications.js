function postApplication(app) {
  return new Promise((resolve) => {
    const postData = JSON.stringify(app);
    const req = https.request(`${API_BASE}/Applications`, {
      method: 'POST',
      agent,
      timeout: 8000,
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(postData)
      }
    }, (res) => {
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => {
        resolve({ success: res.statusCode >= 200 && res.statusCode < 300, status: res.statusCode, body, name: `${app.firstName} ${app.lastName}` });
      });
    });

    req.on('timeout', () => req.destroy(new Error('Timed out')));
    req.on('error', (err) => resolve({ success: false, error: err.message, name: `${app.firstName} ${app.lastName}` }));
    req.write(postData);
    req.end();
  });
}

async function seed() {
  console.log(`Starting to seed ${applicationsSeedData.length} application records...`);
  for (const app of applicationsSeedData) {
    const result = await postApplication(app);
    if (result.success) {
      console.log(`✓ ${result.name} (${app.status}) created.`);
    } else {
      console.error(`✗ ${result.name} failed: ${result.error || result.body}`);
    }
  }
  console.log('Seeding finished.');
}

if (process.argv[1] && process.argv[1].endsWith('seed_applications.js')) {
  seed();
}
